# Profundizar en los sistemas de numeración

# Sistema decimal
a = 10
print(f"a decimal: {a}")

# Sistema binario
a = 0b1010
print(f"a binario: {a}")

# Sistema octal
a = 0o12
print(f"a octal: {a}")
    
# Sistema hexadecimal
a = 0xA
print(f"a hexadecimal: {a}")

# base Decimal
a = int('23',10)
print(f"a base decimal: {a}")

# base Binaria
a = int('10111',2)
print(f"a base binaria: {a}")

# base Octal
a = int('27',8)
print(f"a base octal: {a}")

# base Hexadecimal
a = int('17',16)
print(f"a base hexadecimal: {a}")

# base 5 sus valores son de 0 a 4
a = int('344',5)
print(f"a base 5: {a}")